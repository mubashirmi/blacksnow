export function TemplateGallery({ onLoadTemplate }: TemplateGalleryProps) {
    const [selectedCategory, setSelectedCategory] = useState('All');
    const [searchQuery, setSearchQuery] = useState('');

    const filteredTemplates = templates.filter((template) => {
        const matchesCategory = selectedCategory === 'All' || template.category === selectedCategory;
        const matchesSearch =
            searchQuery === '' ||
            template.name.toLowerCase().includes(searchQuery.toLowerCase()) ||
            template.description.toLowerCase().includes(searchQuery.toLowerCase()) ||
            template.category.toLowerCase().includes(searchQuery.toLowerCase());
        return matchesCategory && matchesSearch;
    });

    return (
        <div className='p-4 space-y-4'>
            <div>
                <h3 className='text-lg font-semibold mb-3'>Professional Templates</h3>

                {/* Search */}
                <div className='relative mb-4'>
                    <Search className='absolute left-3 top-1/2 transform -translate-y-1/2 text-muted-foreground w-4 h-4' />
                    <Input placeholder='Search templates...' value={searchQuery} onChange={(e) => setSearchQuery(e.target.value)} className='pl-10' />
                </div>

                {/* Categories */}
                <div className='flex flex-wrap gap-2 mb-4'>
                    {categories.map((category) => {
                        const Icon = category.icon;
                        return (
                            <Button
                                key={category.name}
                                variant={selectedCategory === category.name ? 'default' : 'outline'}
                                size='sm'
                                onClick={() => setSelectedCategory(category.name)}
                                className='text-xs'
                            >
                                <Icon className='w-3 h-3 mr-1' />
                                {category.name}
                            </Button>
                        );
                    })}
                </div>
            </div>

            {/* Templates Grid */}
            <ScrollArea className='h-[600px]'>
                <div className='grid grid-cols-2 gap-3'>
                    {filteredTemplates.map((template) => (
                        <Card key={template.id} className='cursor-pointer hover:shadow-md transition-shadow'>
                            <CardContent className='p-3'>
                                <div className='space-y-1'>
                                    <h4 className='font-medium text-sm'>{template.name}</h4>
                                    <Badge variant='secondary' className='text-xs'>
                                        {template.category}
                                    </Badge>
                                    <p className='text-xs text-muted-foreground line-clamp-2'>{template.description}</p>
                                    <Button size='sm' className='w-full mt-2' onClick={() => onLoadTemplate(template)}>
                                        Use Template
                                    </Button>
                                </div>
                            </CardContent>
                        </Card>
                    ))}
                </div>

                {filteredTemplates.length === 0 && (
                    <div className='text-center py-8 text-muted-foreground'>
                        <p>No templates found matching your criteria.</p>
                    </div>
                )}
            </ScrollArea>
        </div>
    );
}
